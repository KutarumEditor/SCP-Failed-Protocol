function IsPersonaUnique( n, sn )
	local unique = true

	for k, v in ipairs( USED_PERSONAS ) do
		if n == v.name and sn == v.surname then
			unique = false
		end
	end

	return unique
end

function FindPlayerByPersona( n, sn )
	local ply

	for i, v in ipairs( player.GetAll() ) do
		if v:FPName() == n and v:FPSurname() == sn then ply = v end
	end

	return ply
end

local PLAYER = FindMetaTable( "Player" )

function PLAYER:FPName()
	return self:Get_Name()
end

function PLAYER:SetFPName( name )
	self:Set_Name( name )
end

function PLAYER:FPSurname()
	return self:Get_Surname()
end

function PLAYER:SetFPSurname( surname )
	self:Set_Surname( surname )
end

local name_gen_overrides = {
	["classd"] = function( ply )
		local d, code = "D -", ""

		repeat
			code = FPRandom( 1000, 9999 )
		until IsPersonaUnique( d, code )

		ply:SetFPName( d )
		ply:SetFPSurname( code )

		table.insert( USED_PERSONAS, {
			name = d,
			surname = code
		} )

		net.Start( "PersonaSync" )
			net.WriteTable( USED_PERSONAS )
		net.Broadcast()

		return d, code
	end
}

function PLAYER:GeneratePersona( override )
	if override != nil and name_gen_overrides[override] != nil then
		return name_gen_overrides[override]( self )
	else
		local n, sn

		repeat
			n, sn = POSSIBLE_MALE_NAMES[FPRandom( 1, #POSSIBLE_MALE_NAMES )], POSSIBLE_SURNAMES[FPRandom( 1, #POSSIBLE_SURNAMES )]
		until IsPersonaUnique( n, sn )

		self:SetFPName( n )
		self:SetFPSurname( sn )

		table.insert( USED_PERSONAS, {
			name = n,
			surname = sn
		} )

		net.Start( "PersonaSync" )
			net.WriteTable( USED_PERSONAS )
		net.Broadcast()

		return n, sn
	end
end

function PLAYER:ChangePersonaManually( name, surname )
	for k, v in pairs( USED_PERSONAS ) do
		if v.name == self:FPName() and v.surname == self:FPSurname() then
			v.name, v.surname = name, surname
		end
	end

	self:SetFPName( name )
	self:SetFPSurname( surname )

	net.Start( "PersonaSync" )
		net.WriteTable( USED_PERSONAS )
	net.Broadcast()
end